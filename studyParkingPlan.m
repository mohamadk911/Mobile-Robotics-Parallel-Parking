function study = studyParkingPlan(plan,scenario,vehicle,timing,quality,settings)
%studyParkingPlan Numerical study of ONE frozen plan; never calls a planner.
% Main grid and criteria are declared in sensitivitySettings before execution.
% Tracking metrics: analytic plan vs Euler (unchanged production evaluator).
% Numerical metrics: Euler vs tighter continuous-command ode45 reference.
% Additional exact held-command solution separates command sampling from
% Euler state integration; vector differences add, scalar error norms do not.
    if nargin < 6
        settings = sensitivitySettings();
    end
    study = struct('scenario',scenario,'plan',plan,'status','not_applicable', ...
        'message',plan.status.message,'runs',struct([]),'summary',table(), ...
        'convergence',table(),'metricChanges',table(),'checks',struct([]), ...
        'passed',false,'baselineJustified',false,'diagnostic',[], ...
        'reference',[],'refinedReference',[]);
    if ~strcmp(plan.status.code,'feasible') || isempty(plan.segments)
        return
    end
    geometry = validateCubicGeometry(plan.segments,vehicle,'stopped');
    assert(geometry.passed,'studyParkingPlan:InvalidGeometry','%s',geometry.message);
    reference = integrateParkingReference(plan,scenario,vehicle,timing,settings.reference);
    refined = integrateParkingReference(plan,scenario,vehicle,timing,settings.refinedReference);
    allDt = [settings.dt,settings.diagnosticDt];
    parts = cell(1,numel(allDt)); rows = parts;
    for k = 1:numel(allDt)
        currentTiming = timingSettings(timing.segmentDurations,allDt(k));
        trajectory = timeParkingPlan(plan,vehicle,currentTiming);
        euler = simulateParkingPlan(trajectory,scenario,vehicle);
        accurate = sampleParkingReference(refined,trajectory);
        coarseReference = sampleParkingReference(reference,trajectory);
        held = simulateHeldParkingPlan(trajectory,scenario,vehicle);
        evaluation = evaluateParkingExperiment(plan,trajectory,euler,scenario,vehicle,quality);
        numerical = compareParkingStates(euler,accurate);
        stability = compareParkingStates(coarseReference,accurate);
        stateIntegration = compareParkingStates(euler,held);
        commandSampling = compareParkingStates(held,accurate);
        referenceToPlan = compareParkingStates(accurate,trajectory);
        parts{k} = struct('dt',allDt(k),'timing',currentTiming,'planSegments',plan.segments, ...
            'trajectory',trajectory,'euler',euler,'accurate',accurate,'held',held, ...
            'evaluation',evaluation,'numerical',numerical,'referenceStability',stability, ...
            'stateIntegration',stateIntegration,'commandSampling',commandSampling, ...
            'referenceToPlan',referenceToPlan);
        m = evaluation.metrics;
        rows{k} = struct('dt',allDt(k),'samples',numel(euler.t), ...
            'finalPositionError',m.finalPositionError,'finalHeadingError',m.finalHeadingError, ...
            'maxTimeMatchedXYError',m.maxTimeMatchedXYError,'timeWeightedXYRMSE',m.timeWeightedXYRMSE, ...
            'maxGeometricPathDeviation',m.maxGeometricPathDeviation, ...
            'numericalFinalXY',numerical.finalXY,'numericalFinalHeading',numerical.finalHeading, ...
            'numericalMaxXY',numerical.maxXY,'numericalXYRMSE',numerical.timeWeightedXYRMSE, ...
            'stateIntegrationXYRMSE',stateIntegration.timeWeightedXYRMSE, ...
            'commandSamplingXYRMSE',commandSampling.timeWeightedXYRMSE, ...
            'maxSteering',m.maxSteering,'maxAbsCurvature',m.maxAbsCurvature, ...
            'minTurningRadius',m.minTurningRadius,'qualityStatus',string(evaluation.status), ...
            'passed',evaluation.passed);
    end
    count = numel(settings.dt);
    study.runs = [parts{1:count}];
    study.diagnostic = parts{end};
    study.summary = struct2table([rows{1:count}]);
    summary = study.summary;
    study.convergence = parkingConvergence(settings.dt,summary.numericalXYRMSE.',settings.baselineDt);
    changeNames = {'finalPositionError','finalHeadingError','maxTimeMatchedXYError', ...
        'timeWeightedXYRMSE','maxGeometricPathDeviation','numericalFinalXY', ...
        'numericalFinalHeading','numericalMaxXY','numericalXYRMSE', ...
        'stateIntegrationXYRMSE','commandSamplingXYRMSE'};
    changes = cell(1,numel(changeNames));
    for k = 1:numel(changeNames)
        values = summary.(changeNames{k}).';
        change = parkingConvergence(settings.dt,values,settings.baselineDt);
        change.metric = repmat(string(changeNames{k}),height(change),1);
        changes{k} = change;
    end
    study.metricChanges = vertcat(changes{:});
    allRuns = [parts{:}];
    stabilities = [allRuns.referenceStability];
    referenceXYChange = max([stabilities.maxXY]);
    referenceHeadingChange = max([stabilities.maxHeading]);
    c = settings.criteria;
    baseline = find(settings.dt == settings.baselineDt);
    qualityNames = fieldnames(quality);
    budgetFractions = zeros(1,numel(qualityNames));
    for k = 1:numel(qualityNames)
        budgetFractions(k) = summary.(qualityNames{k})(baseline)/quality.(qualityNames{k});
    end
    geometryFixed = all(summary.maxSteering == geometry.maxAbsSteering) && ...
        all(summary.maxAbsCurvature == geometry.maxAbsCurvature) && ...
        all(summary.minTurningRadius == geometry.minTurningRadius);
    stableReference = referenceXYChange <= c.referenceMaxXYChange && ...
        referenceHeadingChange <= c.referenceMaxHeadingChange && ...
        referenceXYChange <= c.referenceFractionOfFinestRMS*summary.numericalXYRMSE(end);
    orders = study.convergence.observedOrder(1:end-1);
    study.checks = [ ...
        check('monotoneNumericalRMS',all(diff(summary.numericalXYRMSE)<0),true, ...
            all(diff(summary.numericalXYRMSE)<0),'XY RMS must strictly decrease with each halving.'), ...
        check('firstOrder',orders,c.orderRange,all(isfinite(orders)) && ...
            all(orders>=c.orderRange(1) & orders<=c.orderRange(2)),'Observed RMS order must be within the predeclared range.'), ...
        check('baselineAndFinerQuality',summary.passed(baseline:end),true, ...
            all(summary.passed(baseline:end)),'Baseline and all finer grids must pass the frozen quality gate.'), ...
        check('baselineQualityBudget',budgetFractions,c.baselineQualityBudgetFraction, ...
            all(isfinite(budgetFractions)) && all(budgetFractions<=c.baselineQualityBudgetFraction), ...
            'Each baseline tracking metric must remain within its frozen POC budget.'), ...
        check('referenceStability',[referenceXYChange,referenceHeadingChange], ...
            [min(c.referenceMaxXYChange,c.referenceFractionOfFinestRMS*summary.numericalXYRMSE(end)), ...
            c.referenceMaxHeadingChange],stableReference,'Tighter ode45 tolerances must give a stable reference.'), ...
        check('geometryInvariant',geometryFixed,true,geometryFixed, ...
            'Continuous curvature, steering and radius must be identical across dt.')];
    study.passed = all([study.checks.passed]);
    study.baselineJustified = study.passed;
    study.status = 'fail';
    study.message = strjoin({study.checks(~[study.checks.passed]).reason},' ');
    if study.passed
        study.status = 'pass';
        study.message = 'Predeclared convergence criteria passed; baseline justified within frozen POC budgets.';
    end
    study.reference = reference;
    study.refinedReference = refined;
end

function c = check(name,value,limit,passed,reason)
    c = struct('name',name,'value',value,'limit',limit,'passed',logical(passed),'reason',reason);
end
